"""Export uv.lock's runtime dependencies to constraints/requirements-lock.txt.

    python scripts/export_constraints.py           # (re)write the file
    python scripts/export_constraints.py --check   # exit 1 if it is stale versus uv.lock

The file pins every runtime dependency of argus-screens (not argus-screens itself and
not the dev group) to the exact version and file hashes that uv.lock resolved. It is
what `uv tool install argus-screens==X --constraints constraints/requirements-lock.txt`
reads. Needs only Python 3.12+ and uv on PATH; run it from anywhere.
"""

from __future__ import annotations

import argparse
import difflib
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TARGET = ROOT / "constraints" / "requirements-lock.txt"

HEADER = """\
# Runtime dependencies of argus-screens pinned to what uv.lock resolved, with file hashes.
# GENERATED by scripts/export_constraints.py. Edit pyproject.toml, run `uv lock`, then
# run `python scripts/export_constraints.py`. CI fails if this file is out of date.
# Use: uv tool install argus-screens==<version> --constraints constraints/requirements-lock.txt
# See docs/enterprise-install.md. (`uv tool install` applies the versions but does not
# verify the hashes; the wheelhouse path does. Both are explained there.)
"""

# --locked: fail if uv.lock doesn't match pyproject.toml, never re-resolve silently.
# No index/find-links lines are emitted, so the file is the same on every machine.
EXPORT = [
    "uv", "export", "--format", "requirements-txt", "--no-dev", "--no-emit-project",
    "--locked", "--no-header",
]


def render() -> str:
    try:
        proc = subprocess.run(EXPORT, cwd=ROOT, capture_output=True, text=True, encoding="utf-8", check=False)
    except FileNotFoundError:
        raise SystemExit("uv is not on PATH. Install it from https://docs.astral.sh/uv/ and retry.") from None
    if proc.returncode != 0:
        raise SystemExit(f"`{' '.join(EXPORT)}` failed:\n{proc.stderr.strip()}")
    return HEADER + proc.stdout.replace("\r\n", "\n")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="don't write; exit 1 if the file is stale")
    args = parser.parse_args()

    wanted = render()
    if args.check:
        current = TARGET.read_text(encoding="utf-8").replace("\r\n", "\n") if TARGET.exists() else ""
        if current == wanted:
            print(f"{TARGET.relative_to(ROOT)} is up to date with uv.lock")
            return 0
        diff = difflib.unified_diff(current.splitlines(), wanted.splitlines(), "committed", "from uv.lock", lineterm="", n=1)
        print("\n".join(list(diff)[:60]))
        print(f"\n{TARGET.relative_to(ROOT)} is stale versus uv.lock. Run: python scripts/export_constraints.py", file=sys.stderr)
        return 1

    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(wanted, encoding="utf-8", newline="\n")
    print(f"wrote {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
